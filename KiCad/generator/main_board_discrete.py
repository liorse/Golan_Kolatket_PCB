"""
Main board, all-discrete version (KiCad/Main_Board_Discrete). Same job, outline, mounting
holes and front-panel link as Main_Board, but every function is built from components on the
board instead of plug-in modules:

  ESP32 DevKit      -> ESP32-WROOM-32E module + CH340C USB-UART + Micro-USB + auto-reset/BOOT/RESET
  DM542T driver     -> TMC2226 stepper driver on the board (1.0 A RMS, 1/64 microstep by pins),
                       motor coils on J2
  Adafruit MAX31856 -> MAX31856 chip with the datasheet input filter, thermocouple terminal J7
  HW-517 MOSFET     -> AOD4184A low-side switch, gate driven at 5 V, heater terminal J6
  off-board LM2596  -> 24 V input with fuse, reverse-polarity diode and TVS, LMR38010 buck to 5 V,
                       AMS1117 LDO to 3.3 V; USB VBUS is diode-OR'ed onto 5 V for bench programming

The GPIO map is identical to the DevKit board. Firmware change needed: steps_per_rev
25600 -> 12800 (1/64 microstepping instead of the DM542T's 1/128).
Parts are chosen for JLCPCB assembly (LCSC numbers in the "LCSC" field).
4 layers: F.Cu signals + GND pour / In1 GND plane / In2 +3V3 plane / B.Cu signals + GND pour.
All coordinates are mm from the board's top-left corner, viewed from the top.

Build (KiCad's python, from KiCad/Main_Board_Discrete):
  1. python ../generator/main_board_discrete.py            schematic + placed, unrouted PCB
  2. python ../generator/route.py Main_Board_Discrete.kicad_pcb <java.exe> <freerouting-1.9.0.jar> 60 \\
         --plane-nets=GND,+3V3 -mt 10
     (GND / +3V3 pads get vias into the planes; Freerouting 1.9.0 routes the signals - 2.x
      crashes in its maze search on this board)
  3. python ../generator/jlc_outputs.py Main_Board_Discrete.kicad_pcb fab   BOM + CPL
  Field-only changes (LCSC numbers etc.): main_board_discrete.py --fields-only keeps the routing.
"""
