def part(ref, lib_id, value, fp, nets, pos, rot=0, group=None, mpn="", lcsc=None, **kw):
    fields = dict(kw.pop("fields", {}))
    if mpn:
        fields["MPN"] = mpn
    key = lcsc if lcsc is not None else (mpn or value)
    if LCSC.get(key):
        fields["LCSC"] = LCSC[key]
    return d.add(ref, lib_id, value, fp, nets, pos=pos, rot=rot, group=group, fields=fields, **kw)


def R(ref, value, a, b, pos, rot=0, group=None, fp=R0603):
    return part(ref, "Device:R", value, fp, {"1": a, "2": b}, pos, rot, group, lcsc="R" + value)


def C(ref, value, a, b, pos, rot=0, group=None, fp=C0603):
    size = {C0805: " 0805", C1206: " 1206"}.get(fp, "")          # same value, different part per size
    key = "C" + value + size if ("C" + value + size) in LCSC else "C" + value
    return part(ref, "Device:C", value, fp, {"1": a, "2": b}, pos, rot, group, lcsc=key)


