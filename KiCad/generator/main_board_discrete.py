# Schematic layout: functional blocks on an A2 sheet, ICs first, small parts in rows below
# ==========================================================================================
GROUP_ORIGIN = {"pwr": (20, 30), "buck": (20, 140), "ldo": (20, 255),
                "mcu": (190, 30), "usb": (190, 178), "auto": (190, 310),
                "step": (340, 30), "mech": (340, 300),
                "tc": (460, 30), "lim": (460, 170), "link": (460, 232), "heat": (600, 30)}
GROUP_WIDTH = {"mcu": 140, "auto": 140, "step": 110}
SMALL = ("Device:", "Switch:", "Transistor_BJT:", "Mechanical:")


def extents(p):
    """(left, up, right, down) reach of a symbol incl. pin stubs and labels, from its origin (mm)."""
    sym = kigen.get_symbol(p.lib_id)
    bx0, by0, bx1, by1 = kigen.symbol_bbox(sym)
    l, u, r, dn = -bx0 + 2, by1 + 2, bx1 + 2, -by0 + 2
    for num, name, px, py, ang in kigen.symbol_pins(sym):
        net = p.nets.get(num)
        reach = kigen.STUB + (8.0 if net in kigen.POWER_SYMBOLS else kigen._label_len(net) if net else 1.5)
        a = int(ang) % 360
        if a == 0:
            l = max(l, -px + reach)
        elif a == 180:
            r = max(r, px + reach)
        elif a == 90:
            dn = max(dn, -py + reach)
        else:
            u = max(u, py + reach)
    if not kigen.symbol_pins(sym) or all(int(a) in (90, 270) for *_, a in kigen.symbol_pins(sym)):
        r += kigen._label_len(p.value) + 3          # reference / value text beside vertical parts
    return l, u, r, dn


def layout_schematic():
    """Each block: ICs/connectors in a row, small parts in wrapped rows below. Spacing comes from
    each symbol's real reach (pins + stubs + labels), so no two parts' wires or labels can touch."""
    by_group = {}
    for p in d.parts:
        if p.sch is None:
            by_group.setdefault(p.group, []).append(p)
    for g, parts in by_group.items():
        ox, oy = GROUP_ORIGIN[g]
        width = GROUP_WIDTH.get(g, 110)
        big = [p for p in parts if not p.lib_id.startswith(SMALL)]
        small = [p for p in parts if p.lib_id.startswith(SMALL)]
        y = oy + 6
        for row in (big, small):
            x, row_u, row_d, placed = ox, 0, 0, []
            for p in row:
                l, u, r, dn = extents(p)
                if placed and x + l + r > ox + width:
                    for q, qu in placed:
                        q.sch = (q.sch[0], y + row_u)
                    y += row_u + row_d + 5
                    x, row_u, row_d, placed = ox, 0, 0, []
                p.sch = (x + l, 0)
                placed.append((p, u))
                x += l + r + 2.54
                row_u, row_d = max(row_u, u), max(row_d, dn)
            for q, qu in placed:
                q.sch = (q.sch[0], y + row_u)
            if placed:
                y += row_u + row_d + 5


