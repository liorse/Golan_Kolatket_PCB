"""
Front panel board: 2.8" ST7789/ILI9341 SPI TFT (MSP2807 outline) + 4 Cherry MX keys
on SparkFun Cherry MX breakout boards (plugged into 1x4 sockets).
Linked to the main board by two 6-pin 5.08 mm Phoenix MSTB pluggable terminals (J1, J2).

All coordinates are in mm from the board's top-left corner, viewed from the front (top layer).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kigen
import peeling_lib
from link_pinout import LINK_A, LINK_B

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Front_Panel")
NAME = "Front_Panel"

peeling_lib.ensure()
d = kigen.Design(NAME, "Peeling Instrument - Front Panel", rev="A",
                 company="Weizmann Institute",
                 comments=["2.8in SPI TFT (MSP2807 outline) + 4x Cherry MX on SparkFun BOB-13773",
                           "Link to main board: J1/J2 Phoenix MSTB 2,5/6-G-5,08",
                           "Generated by KiCad/generator/front_panel.py"])

BOARD_W, BOARD_H = 150.0, 90.0
d.groups = [("link", "LINK TO MAIN BOARD"), ("disp", "DISPLAY  2.8in SPI TFT (MSP2807)"),
            ("keys", "KEYS  Cherry MX on SparkFun BOB-13773 breakouts"), ("mech", "MECHANICAL")]
d.flag_pos, d.flag_group = (40.64, 114.3), "link"      # PWR_FLAGs for GND / +3V3 (ERC)

# ---- Board-to-board link (pluggable, plug enters from the top edge) -------------
# Mounted on the BACK (side "B"): headers are inserted from the back and soldered on the display side,
# so the cables leave behind the panel. Body overhangs the top edge, plug enters from the top.
# Seen from the front, pad 1 is the left-most pin.
PH = "Connector_Phoenix_MSTB:PhoenixContact_MSTBA_2,5_6-G-5,08_1x06_P5.08mm_Horizontal"
P, TOP_Y = 5.08, 10.4
LINK_X = (46.6, 82.6)                 # pin 1 of J1 / J2 (left-most pin seen from the front)
d.add("J1", "Connector_Generic:Conn_01x06", "LINK_A", PH, LINK_A, pos=(LINK_X[0], TOP_Y), rot=0, side="B",
      sch=(60.96, 50.8), group="link")
d.add("J2", "Connector_Generic:Conn_01x06", "LINK_B", PH, LINK_B, pos=(LINK_X[1], TOP_Y), rot=0, side="B",
      sch=(60.96, 83.82), group="link")

# ---- Display ---------------------------------------------------------------------
# MSP2807 module 86 x 50 mm, mounted landscape, header on the right, pin 1 at the bottom.
# Module top-left corner on the board:
DX, DY = 32.0, 22.5
# 14-pin header: column 2.00 mm from the module's right edge, pin 1 at 41.51 mm, pin 14 at 8.49 mm
disp_nets = {"1": "+3V3", "2": "GND", "3": "TFT_CS", "4": "TFT_RST", "5": "TFT_DC",
             "6": "SPI_MOSI", "7": "SPI_SCK", "8": "TFT_BL"}   # 9 SDO and 10-14 touch: not connected
d.add("U1", "Peeling:TFT_2.8in_SPI_MSP2807", "TFT_2.8in_SPI",
      "Connector_PinSocket_2.54mm:PinSocket_1x14_P2.54mm_Vertical", disp_nets,
      pos=(DX + 84.0, DY + 41.51), rot=180, sch=(147.32, 68.58), group="disp")
# 4-pin SD-card header on the opposite edge: not wired, its socket is a mechanical support.
# Position counted on the working perfboard prototype (2.54 mm grid, photo IMG_8478):
#   SD column ~78.35 mm from the 14-pin column: at 31 pitches (78.74) the pin tips landed ~0.4 mm short of the pad\n#   centres toward the display centre on the 1:1 print (photo IMG_8481); not on the 2.54 grid
#   4 holes between the bottom 14-pin pin (VCC) and the first SD pin -> 5 pitches = 12.7 mm
# i.e. the SD header is centred on the 14-pin header (rows 6-9 counted from VCC).
SD_DX, SD_DY = 78.35, 0.37         # +0.37: pins sat 0.37 mm below the pad centres on the 1:1 print (IMG_8484)         # SD header centre relative to the 14-pin header centre
d.add("J4", "Connector_Generic:Conn_01x04", "TFT_SD_support",
      "Connector_PinSocket_2.54mm:PinSocket_1x04_P2.54mm_Vertical", {},
      pos=(DX + 84.0 - SD_DX, DY + 25.0 + SD_DY - 3.81), rot=0, sch=(187.96, 58.42), group="disp",
      fields={"Description": "Support socket for the display SD header (not wired). Verify position on the module."})
# Display mounting holes (module: 4x d3.2 on 76.08 x 44.00) for optional standoffs
for i, (hx, hy) in enumerate([(4.96, 3.0), (81.04, 3.0), (4.96, 47.0), (81.04, 47.0)], 5):
    d.add("H%d" % i, "Mechanical:MountingHole", "Display_standoff",
          "MountingHole:MountingHole_3.2mm_M3", {}, pos=(DX + hx, DY + hy),
          sch=(162.56 + 25.4 * (i - 5), 99.06), group="disp")

# ---- Keys: Cherry MX switches on SparkFun breakouts (BOB-13773, 19.05 mm square).
# Each breakout plugs into two 1x4 female sockets 15.24 mm apart (one per side header).
# Breakout header order, top to bottom: "2", "1", LED-, LED+  ->  socket pin 1 = GND, pin 2 = BTN_x.
# Both side sockets are wired in parallel; LED pins are unused.
# The switches themselves (SW1-SW4) are schematic-only: they arrive on the breakouts.
# Screen labels: A top-left, B bottom-left, X top-right, Y bottom-right.
SOCK4 = "Connector_PinSocket_2.54mm:PinSocket_1x04_P2.54mm_Vertical"
# Key rows aligned with the display module: top edge of the upper breakouts = top of the display
# PCB, bottom edge of the lower breakouts = bottom of the display PCB (breakouts are 19.05 mm square).
KEY_HALF = 19.05 / 2
KEY_TOP_Y, KEY_BOT_Y = DY + KEY_HALF, DY + 50.0 - KEY_HALF
KEYS = [("SW1", "BTN_A", "A_START_STOP", (18.0, KEY_TOP_Y)),
        ("SW2", "BTN_B", "B_SET_HOME", (18.0, KEY_BOT_Y)),
        ("SW3", "BTN_X", "X_PLUS_CAL", (135.0, KEY_TOP_Y)),
        ("SW4", "BTN_Y", "Y_MINUS", (135.0, KEY_BOT_Y))]
key_silk = []
jn = 5
for k, (ref, net, val, (cx, cy)) in enumerate(KEYS):
    ky = 50.8 + 22.86 * k
    d.add(ref, "Switch:SW_Push", val, None, {"1": net, "2": "GND"},
          fields={"Description": "Cherry MX on SparkFun BOB-13773, plugs into sockets"},
          sch=(276.86, ky), group="keys")
    for s_i, (side, sx) in enumerate((("L", cx - 7.62), ("R", cx + 7.62))):
        d.add("J%d" % jn, "Connector_Generic:Conn_01x04", "%s_%s_socket" % (ref, side), SOCK4,
              {"1": "GND", "2": net}, pos=(sx, cy - 3.81), sch=(325.12 + 38.1 * s_i, ky), group="keys")
        jn += 1
    key_silk.append((cx, cy))

# ---- Panel mounting holes ----------------------------------------------------------
for i, (hx, hy) in enumerate([(4.0, 4.0), (146.0, 4.0), (4.0, 86.0), (146.0, 86.0)], 1):
    d.add("H%d" % i, "Mechanical:MountingHole", "M3", "MountingHole:MountingHole_3.2mm_M3", {},
          pos=(hx, hy), sch=(40.64 + 15.24 * (i - 1), 147.32), group="mech")

d.texts.append((30.48, 172.72,
                "Display: MSP2807-type 2.8in 240x320 SPI module, 14-pin header.\n"
                "SDO (pin 9) and touch pins 10-14 are left open: the display SDO is not\n"
                "guaranteed to tri-state and would share SPI_MISO with the MAX31856.\n"
                "No pull-ups on BTN_x: the ESP32 internal pull-ups are used, and BTN_Y is\n"
                "GPIO12 (strapping pin) which must not be pulled high at boot."))

if __name__ == "__main__":
    import pcbnew
    os.makedirs(OUT, exist_ok=True)
    base = os.path.join(OUT, NAME)
    kigen.write_project(d, base + ".kicad_pro",
                        {"Default": dict(track_width=0.3, clearance=0.2),
                         "Power": dict(track_width=0.6, clearance=0.25)},
                        [("+3V3", "Power"), ("GND", "Power"), ("TFT_BL", "Power")])
    kigen.write_fp_lib_table(OUT)
    kigen.write_sym_lib_table(OUT)
    kigen.write_schematic(d, base + ".kicad_sch")
    S = pcbnew.F_SilkS
    texts = [(75.0, 84.0, "PEELING INSTRUMENT - FRONT PANEL  rev A", 1.5, S),
             # link terminal titles, beside each terminal
             (LINK_X[0] - 5.1, TOP_Y, "LINK_A\n<- main J4\n(on back)", 1.0, S, 0, "right"),
             (LINK_X[1] + 5 * P + 5.1, TOP_Y, "LINK_B\n<- main J5\n(on back)", 1.0, S, 0, "left"),
             # display module outline label and SD header note
             (DX + 40.0, DY + 25.0, "2.8in SPI TFT (MSP2807)\nheader on the right ->", 1.5, S),
             (DX + 84.0 - SD_DX + 2.2, DY + 25.0 + SD_DY, "SD header\nsupport only\n(not wired)", 0.8, S, 0, "left")]
    # link terminals: signal name under every pin (rot 180 -> pin 1 is the right-most)
    for x1, pins in zip(LINK_X, (LINK_A, LINK_B)):
        for i in range(1, 7):
            texts.append((x1 + P * (i - 1), TOP_Y + 3.4, pins[str(i)], 0.8, S, 90, "right"))
            # same names on the back silkscreen, for wiring from behind (B.SilkS text is mirrored)
            texts.append((x1 + P * (i - 1), TOP_Y + 3.4, pins[str(i)], 0.8, pcbnew.B_SilkS, 90, "left"))
    texts += [(LINK_X[0] + 2.5 * P, TOP_Y + 12.0, "LINK_A -> main J4", 1.0, pcbnew.B_SilkS),
              (LINK_X[1] + 2.5 * P, TOP_Y + 12.0, "LINK_B -> main J5", 1.0, pcbnew.B_SilkS)]
    # display header: the module's own pin names (pin 1 at the bottom)
    disp_pins = ["VCC", "GND", "CS", "RESET", "DC", "SDI", "SCK", "LED",
                 "SDO nc", "T_CLK nc", "T_CS nc", "T_DIN nc", "T_DO nc", "T_IRQ nc"]
    for i, lab in enumerate(disp_pins):
        texts.append((DX + 84.0 - 1.9, DY + 41.51 - 2.54 * i, lab, 0.8, S, 0, "right"))
    rects = [(DX, DY, DX + 86.0, DY + 50.0, S)]                                           # display module outline
    funcs = {"SW1": "A  START/STOP", "SW2": "B  SET/HOME", "SW3": "X  + / CAL", "SW4": "Y  -"}
    for (ref, net, val, _), (cx, cy) in zip(KEYS, key_silk):
        rects.append((cx - 9.525, cy - 9.525, cx + 9.525, cy + 9.525, S))               # breakout outline
        texts.append((cx, cy - 11.2, "%s  %s" % (ref, funcs[ref]), 1.0, S))
        texts.append((cx, cy + 11.2, "2=GND  1=%s" % net, 0.8, S))
        for i, lab in enumerate("21-+"):                                                   # breakout pin labels
            texts.append((cx - 5.4, cy - 3.81 + 2.54 * i, lab, 0.8, S))
            texts.append((cx + 5.4, cy - 3.81 + 2.54 * i, lab, 0.8, S))
    kigen.build_pcb(d, base + ".kicad_pcb", (BOARD_W, BOARD_H), corner_radius=3.0,
                    silk_texts=texts, silk_rects=rects)
    print("written", base)
