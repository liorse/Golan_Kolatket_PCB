"""
Main board: ESP32 30-pin DevKit V1, Adafruit MAX31856 breakout and the dual-MOSFET
(D4184) heater module, all plugged into female headers, plus 5.08 mm pluggable
terminals for field wiring and the front-panel link.

Power concept
  * 6-7 V from the off-board LM2596 buck -> J1 -> ESP32 DevKit VIN (its AMS1117 makes 3V3).
  * 24 V never enters this board: the PSU feeds the DM542T directly, and the 24 V supply and
    heater wires go straight to the MOSFET module's own screw terminals.
  * The board only sends the module its trigger signal (GPIO32) and GND.

GPIO map = Peeling_Automation_Stepper_esp32.ino (source of truth).
All coordinates are in mm from the board's top-left corner, viewed from the top.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kigen
import peeling_lib
from link_pinout import LINK_A, LINK_B

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Main_Board")
NAME = "Main_Board"

peeling_lib.ensure()
VERSION = "1.0"
DATE, DATE_ISO = "17 November 2026", "2026-11-17"
COMPANY = "Physics Core Facilities, Weizmann Institute of Science"
CREDIT = "Lab Automation Unit - Dr. Lior Segev"
LOGO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "WIS_logo.png")
d = kigen.Design(NAME, "2D Exfoliator - Main Board", rev=VERSION,
                 company=COMPANY,
                 comments=[CREDIT,
                           "ESP32 DevKit V1 (30-pin) + Adafruit MAX31856 + D4184 dual-MOSFET module",
                           "Field wiring: Phoenix MSTB 2,5/x-G-5,08 pluggable terminals (5.08 mm)",
                           "Generated by KiCad/generator/main_board.py"])

BOARD_W, BOARD_H = 113.5, 95.0
# Phoenix MSTB 2,5/x-G-5,08 headers (e.g. 1757051 = 6-pin); KiCad footprint family MSTBA, same pin layout
PH = "Connector_Phoenix_MSTB:PhoenixContact_MSTBA_2,5_%d-G-5,08_1x%02d_P5.08mm_Horizontal"
P = 5.08                              # terminal pitch
SOCK = "Connector_PinSocket_2.54mm:PinSocket_%s_P2.54mm_Vertical"

# Schematic blocks (titled boxes on the sheet)
d.date = DATE_ISO
d.groups = [("pwr", "POWER INPUT  6-7 V from the off-board buck"),
            ("mcu", "ESP32 DevKit V1 (30-pin, in sockets)"),
            ("boot", "BOOT CAPACITOR (plug-in)"),
            ("tc", "THERMOCOUPLE  MAX31856 breakout"),
            ("heat", "HEATER  HW-517 MOSFET module"),
            ("step", "STEPPER DRIVER  DM542T"),
            ("lim", "LIMIT SWITCHES"),
            ("link", "FRONT-PANEL LINK"),
            ("mech", "MECHANICAL")]
d.flag_pos, d.flag_group = (91.44, 53.34), "pwr"      # PWR_FLAGs for GND / +3V3 (ERC)

# ---- Field terminals along the top edge (rot 180: pin 1 right-most, plug enters from the top).
# Packed ~1 mm courtyard-to-courtyard so the MAX31856 fits in the same row on the right.
TOP_Y = 10.4
TERMS = [("J1", "POWER_IN_6-7V", {"1": "+VIN", "2": "GND"}, 17.16, ["+VIN", "GND"], "pwr", (60.96, 50.8)),
         # DM542T inputs in the driver's own order; every minus input gets its own GND return
         ("J2", "DM542T", {"1": "STEP_PUL", "2": "GND", "3": "STEP_DIR", "4": "GND",
                           "5": "STEP_ENA", "6": "GND"}, 51.76,
          ["PUL+", "PUL-", "DIR+", "DIR-", "ENA+", "ENA-"], "step", (358.14, 50.8)),
         ("J3", "LIMIT_SW", {"1": "LIMIT_X", "2": "GND", "3": "LIMIT_Y", "4": "GND"}, 76.20,
          ["LIM X", "GND", "LIM Y", "GND"], "lim", (358.14, 91.44))]
for ref, val, nets, x, _, grp, sch in TERMS:
    n = len(nets)
    d.add(ref, "Connector_Generic:Conn_01x%02d" % n, val, PH % (n, n), nets, pos=(x, TOP_Y), rot=180,
          sch=sch, group=grp)

# ---- Front-panel link along the bottom edge (rot 0: pin 1 left-most, plug enters from below)
# Pin-for-pin with Front_Panel J1 (LINK_A) / J2 (LINK_B): wire 1-1, 2-2, ... 6-6.
BOT_Y = BOARD_H - 10.4
LINK_X = (25.58, 59.68)               # pin 1 of J4 / J5
d.add("J4", "Connector_Generic:Conn_01x06", "LINK_A", PH % (6, 6), LINK_A, pos=(LINK_X[0], BOT_Y), rot=0,
      sch=(358.14, 137.16), group="link")
d.add("J5", "Connector_Generic:Conn_01x06", "LINK_B", PH % (6, 6), LINK_B, pos=(LINK_X[1], BOT_Y), rot=0,
      sch=(358.14, 172.72), group="link")

# ---- ESP32 DevKit V1, 30-pin, rows 25.4 mm apart, in two 1x15 female sockets (one footprint).
# Mounted with USB toward the left edge: pins 1 (EN) and 16 (D23) at the antenna end, on the right.
ESP_X1, ESP_Y = 49.56, 29.0          # pad 1 (EN); the D23..3V3 row is 25.4 mm lower
ESP_NETS = {"1": "ESP_EN", "6": "HEATER_PWM", "7": "BTN_B", "8": "STEP_DIR", "9": "STEP_ENA",   # EN D32 D33 D25 D26
            "10": "STEP_PUL", "11": "BTN_X", "12": "BTN_Y", "13": "LIMIT_X",                   # D27 D14 D12 D13
            "14": "GND", "15": "+VIN",                                                          # GND VIN
            "16": "SPI_MOSI", "17": "TC_DRDY", "20": "TC_CS", "21": "SPI_MISO",                 # D23 D22 D21 D19
            "22": "SPI_SCK", "23": "TFT_CS", "24": "TFT_DC", "25": "TFT_BL",                    # D18 D5 IO17 IO16
            "26": "BTN_A", "27": "TFT_RST", "28": "LIMIT_Y", "29": "GND", "30": "+3V3"}         # D4 D2 D15 GND 3V3
d.add("U1", "Peeling:ESP32_DevKit_V1_30pin", "ESP32_DevKit_V1_30pin",
      "Peeling:ESP32_DevKit_V1_30pin_Socket", ESP_NETS, pos=(ESP_X1, ESP_Y), rot=270,
      sch=(162.56, 99.06), group="mcu")

# ---- Adafruit MAX31856 breakout (24.13 x 21.59 mm) in the top row, right of J3, thermocouple
# terminal facing the top edge; its 9-pin header runs left-to-right along the breakout's lower edge.
# Header: VIN 3Vo GND SCK SDO SDI CS FLT DRDY (pin 1 left).
MAX_W, MAX_H = 24.13, 21.59
MX, MY = 81.0, 1.0                   # breakout top-left on the board
MAX_PIN_Y = MY + MAX_H - 2.54
d.add("U2", "Peeling:Adafruit_MAX31856_Breakout", "Adafruit_MAX31856", SOCK % "1x09",
      {"1": "+3V3", "3": "GND", "4": "SPI_SCK", "5": "SPI_MISO", "6": "SPI_MOSI",
       "7": "TC_CS", "9": "TC_DRDY"},
      pos=(MX + 1.905, MAX_PIN_Y), rot=90, sch=(264.16, 63.5), group="tc")
for i, (hx, hy, sy) in enumerate([(2.54, 2.41, 55.88), (21.59, 2.41, 71.12)], 5):
    d.add("H%d" % i, "Mechanical:MountingHole", "MAX31856_standoff",
          "MountingHole:MountingHole_2.7mm_M2.5", {}, pos=(MX + hx, MY + hy),
          sch=(289.56, sy), group="tc")

# ---- HW-517 / D4184 dual-MOSFET module (33.8 x 16.9 mm), plugged by its J1 row of four
# 2.54 mm pins. Top view, J1 toward you: TRIG/PWM, TRIG/PWM, GND, GND (left to right).
# Mounted top-right under the MAX31856, pointing right: screw-terminal end overhangs the right
# board edge by MOS_OVER mm so the 24 V / heater wires never cross the board; J1 end toward the
# left -> top-to-bottom TRIG, TRIG, GND, GND.
MOS_L, MOS_W, MOS_OVER = 33.8, 16.9, 13.0
MOS_X, MOS_Y = BOARD_W + MOS_OVER - MOS_L, 31.0     # module outline top-left
MOS_PIN_X, MOS_PIN_Y = MOS_X + 4.5, MOS_Y + 4.64
d.add("U3", "Peeling:HW-517_MOSFET_Module", "HW-517_MOSFET", SOCK % "1x04",
      {"1": "HEATER_PWM", "2": "HEATER_PWM", "3": "GND", "4": "GND"},
      pos=(MOS_PIN_X, MOS_PIN_Y), rot=0, sch=(264.16, 116.84), group="heat")

# ---- EN-to-GND capacitor: delays the ESP32 reset release at power-up so it boots reliably
# (same fix as on the prototype breadboard). Electrolytic: + to EN, - to GND.
# The capacitor plugs into a 2-pin socket (like on the breadboard); C1 itself is schematic-only.
CAP_X, CAP_Y = 61.0, 52.0
d.add("J10", "Connector_Generic:Conn_01x02", "EN_CAP_socket", SOCK % "1x02",
      {"1": "ESP_EN", "2": "GND"}, pos=(CAP_X, CAP_Y), rot=0,
      fields={"Description": "Socket for the EN boot capacitor: pin 1 = + (EN), pin 2 = - (GND)"},
      sch=(60.96, 91.44), group="boot")
d.add("C1", "Device:C_Polarized", "10uF", None, {"1": "ESP_EN", "2": "GND"},
      fields={"Description": "ESP32 EN boot-delay electrolytic, user-supplied, plugs into J10"},
      sch=(83.82, 93.98), group="boot")

# ---- Board mounting holes
for i, (hx, hy) in enumerate([(4.0, 4.0), (BOARD_W - 4.0, 4.0), (4.0, 91.0), (BOARD_W - 4.0, 91.0)], 1):
    d.add("H%d" % i, "Mechanical:MountingHole", "M3", "MountingHole:MountingHole_3.2mm_M3", {},
          pos=(hx, hy), sch=(40.64 + 15.24 * (i - 1), 147.32), group="mech")
d.texts.append((30.48, 172.72,
                "Power: 6-7 V from the off-board LM2596 buck enters at J1 and feeds the ESP32 DevKit VIN;\n"
                "the DevKit's own regulator supplies +3V3 to the MAX31856 and the front panel.\n"
                "24 V does not enter this board: the PSU feeds the DM542T directly, and the 24 V supply and\n"
                "heater connect to the MOSFET module's own screw terminals (VIN+/VIN-, OUT+/OUT-).\n"
                "U3: the module's J1 row (TRIG/PWM x2, GND x2) plugs into a 1x4 female socket.\n"
                "U1/U2/U3 are plug-in modules: their footprints are female sockets.\n"
                "DM542T: J2 = PUL+, PUL-, DIR+, DIR-, ENA+, ENA- (driver order); each minus pin is GND."))

if __name__ == "__main__":
    import pcbnew
    os.makedirs(OUT, exist_ok=True)
    base = os.path.join(OUT, NAME)
    kigen.write_project(d, base + ".kicad_pro",
                        {"Default": dict(track_width=0.3, clearance=0.2),
                         "Power": dict(track_width=0.6, clearance=0.25)},
                        [("+VIN", "Power"), ("+3V3", "Power"), ("GND", "Power"), ("TFT_BL", "Power")])
    kigen.write_fp_lib_table(OUT)
    kigen.write_sym_lib_table(OUT)
    kigen.write_schematic(d, base + ".kicad_sch")

    S = pcbnew.F_SilkS
    # name / credits block on the component side, logo on its left (logo flush with the text block)
    TX, TY = 83.0, 54.0
    texts = [(TX, TY, "2D EXFOLIATOR - MAIN BOARD", 1.2, S, 0, "left"),
             (TX, TY + 2.8, "v" + VERSION + "   " + DATE, 0.9, S, 0, "left"),
             (TX, TY + 4.9, "Designed by Physics Core Facilities,", 0.9, S, 0, "left"),
             (TX, TY + 7.0, "Weizmann Institute of Science", 0.9, S, 0, "left"),
             (TX, TY + 9.1, "Lab Automation Unit", 0.9, S, 0, "left"),
             (TX, TY + 11.2, "Dr. Lior Segev", 0.9, S, 0, "left"),
             (LINK_X[0] + 2.5 * P, 73.5, "LINK_A -> front J1", 1.0, S),
             (LINK_X[1] + 2.5 * P, 73.5, "LINK_B -> front J2", 1.0, S),
             (31.8, ESP_Y + 12.7, "ESP32 DevKit V1 30-pin\n<- USB", 1.5, S),
             (MX + MAX_W / 2, MY + 9.0, "MAX31856\nTC ^", 1.2, S),
             (BOARD_W - 3.0, MOS_Y + MOS_W / 2, "HW-517 MOSFET", 0.9, S, 90),
             (BOARD_W - 10.5, MOS_Y - 1.6, "24V/heater -> off edge", 0.8, S),
             (MOS_PIN_X, MOS_PIN_Y + 10.4, "J1", 0.8, S)]
    for ref, val, nets, x, labels, _, _ in TERMS:              # pin labels under the top terminals
        for i, lab in enumerate(labels):
            texts.append((x - P * i, 14.3, lab, 0.8, S))
        texts.append((x - P * (len(labels) - 1) / 2.0, 16.3, val, 1.0, S))

    def net_of(ref, pin):
        return next(p for p in d.parts if p.ref == ref).nets.get(pin)
    # ESP32 sockets: connected net beside every used pin, outside the module so it stays visible
    for first, anchor, just in ((1, ESP_Y - 2.2, "left"), (16, ESP_Y + 27.5, "right")):
        for i in range(15):
            n = net_of("U1", str(first + i))
            if n:
                texts.append((ESP_X1 - 2.54 * i, anchor, n, 0.8, S, 90, just))
    # MAX31856 socket: vertical labels below the header, outside the breakout
    for i in range(1, 10):
        n = net_of("U2", str(i))
        if n:
            texts.append((MX + 1.905 + 2.54 * (i - 1), MY + MAX_H + 0.6, n, 0.8, S, 90, "right"))
    # Front-panel link terminals: vertical labels above each pin
    for ref, x0, pins in (("J4", LINK_X[0], LINK_A), ("J5", LINK_X[1], LINK_B)):
        for i in range(1, 7):
            texts.append((x0 + P * (i - 1), BOT_Y - 2.9, pins[str(i)], 0.8, S, 90, "left"))
    texts += [(CAP_X + 1.9, CAP_Y, "+ EN", 0.8, S, 0, "left"),
              (CAP_X + 1.9, CAP_Y + 2.54, "- GND", 0.8, S, 0, "left"),
              (CAP_X + 1.0, CAP_Y + 5.0, "BOOT CAP", 0.8, S)]
    # MOSFET module J1: the module's own pin names
    for i, lab in enumerate(["TRIG/PWM", "TRIG/PWM", "GND", "GND"]):
        texts.append((MOS_X - 0.6, MOS_PIN_Y + 2.54 * i, lab, 0.8, S, 0, "right"))
    rects = [(6.03, ESP_Y - 1.45, 57.53, ESP_Y + 26.85, S),              # ESP32 DevKit outline (approx. 51.5 x 28.3)
             (MX, MY, MX + MAX_W, MY + MAX_H, S),         # MAX31856 breakout
             (MOS_X, MOS_Y, BOARD_W - 1.0, MOS_Y + MOS_W, S)]   # MOSFET module (on-board part)
    # logo: same height as the text block's ink (title cap top .. last line bottom), right edge
    # 1.7 mm left of the text
    top = TY - 1.2 / 2 - 1.2 * 0.075
    bot = TY + 11.2 + 0.9 / 2 + 0.9 * 0.075
    LH = bot - top
    LW = LH * 3339.0 / 2979.0
    logo = (LOGO, TX - 1.7 - LW / 2, (top + bot) / 2, LH, S)
    kigen.build_pcb(d, base + ".kicad_pcb", (BOARD_W, BOARD_H), corner_radius=3.0,
                    silk_texts=texts, silk_rects=rects,
                    silk_logos=[logo])
    print("written", base)
